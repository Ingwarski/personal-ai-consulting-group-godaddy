async (page) => {
  const result = { scope: "Loopback fixture: shipped template/client/CSS and in-memory settings domain. No production auth, database, provider execution, or representative-user validation.", checks: {}, viewports: [] };
  const check = (name, value) => { result.checks[name] = Boolean(value); if (!value) throw new Error("Failed: " + name); };
  await page.unroute("**/*");
  await page.route("**/*", route => route.request().url().startsWith("http://127.0.0.1:4321/") ? route.continue() : route.abort());
  const provider = page.getByRole("combobox", { name: "Провайдер Критика", exact: true });
  const head = page.locator("#codex-effort");
  const critic = page.locator("#critic-effort");
  const observations = () => page.evaluate(async () => (await fetch("/__fixture/observations")).json());
  const mutations = value => value.requests.filter(request => request.method !== "GET").length;
  const before = await observations();
  await provider.focus();
  await provider.selectOption("claude_code");
  check("provider_focus_retained", await provider.evaluate(node => document.activeElement === node));
  await critic.selectOption("medium");
  await provider.selectOption("codex");
  check("inactive_codex_low_restored", await critic.inputValue() === "low");
  await critic.selectOption("xhigh");
  await provider.selectOption("claude_code");
  check("claude_draft_medium_retained", await critic.inputValue() === "medium");
  await provider.selectOption("codex");
  check("codex_draft_xhigh_retained", await critic.inputValue() === "xhigh");
  check("head_high_unchanged", await head.inputValue() === "high");
  check("no_autosave", mutations(await observations()) === mutations(before));
  check("extra_high_label", (await critic.locator("option:checked").textContent()) === "Extra High");
  check("exactly_three_groups", await page.locator(".settings-group").count() === 3);
  await Promise.all([page.waitForNavigation(), page.getByRole("button", { name: "Зберегти весь набір" }).click()]);
  const saved = await observations();
  check("one_explicit_save", mutations(saved) === mutations(before) + 1);
  check("both_preferences_persisted", saved.settings.critic.claude.reasoningEffort === "medium" && saved.settings.critic.codex.reasoningEffort === "xhigh" && saved.settings.codex.reasoningEffort === "high" && saved.settings.critic.provider === "codex");
  check("save_reload_restores_codex", await provider.inputValue() === "codex" && await critic.inputValue() === "xhigh");
  for (const width of [1440, 1280, 768, 430, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    const geometry = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, groups: document.querySelectorAll(".settings-group").length }));
    check("reflow_" + width, geometry.scrollWidth <= width && geometry.groups === 3);
    const path = "output/playwright/critic-router-20260906/settings-" + width + ".png";
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path, fullPage: true });
    result.viewports.push({ ...geometry, screenshot: path });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("http://127.0.0.1:4321/settings?scenario=no-claude");
  check("missing_claude_keeps_codex_valid", (await page.locator("#settings-status").getAttribute("class")).includes("success"));
  check("invalid_default_reset_disabled", await page.getByRole("button", { name: "Повернути default" }).isDisabled());
  await provider.focus();
  await provider.selectOption("claude_code");
  check("missing_claude_selector_enabled_focused", await provider.isEnabled() && await provider.evaluate(node => document.activeElement === node));
  check("missing_claude_saved_value_retained", await page.locator("#critic-model").inputValue() === "claude-current-critic" && await critic.inputValue() === "medium");
  check("missing_claude_blocks_save", await page.getByRole("button", { name: "Зберегти весь набір" }).isDisabled());
  check("missing_claude_recovery_visible", await page.locator("#critic-recovery-link").isVisible());
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: "output/playwright/critic-router-20260906/missing-claude-390.png", fullPage: true });
  await provider.selectOption("codex");
  check("codex_recovers_without_claude", await critic.inputValue() === "xhigh" && (await page.locator("#settings-status").getAttribute("class")).includes("success"));
  await page.goto("http://127.0.0.1:4321/settings?scenario=expired");
  check("expired_catalog_blocks_save", await page.getByRole("button", { name: "Зберегти весь набір" }).isDisabled());
  check("expired_catalog_recovery_visible", await page.locator("#critic-recovery-link").isVisible());
  check("fixture_external_provider_calls_zero", (await observations()).externalProviderCalls === 0);
  result.savedSettings = saved.settings;
  return result;
}
